"""Reduced-order coupled-circuit transient model for a shared Mono Spiral PI coil.

This is a parameterized engineering model, NOT an FEM solution.
The target is represented by one equivalent shorted RL loop coupled to the
search winding. Target R/L/M must come from a defined target geometry or
measurement before any physical sensitivity claim is made.
"""
from __future__ import annotations

from dataclasses import dataclass
import math
from typing import Iterable


@dataclass(frozen=True)
class Coil:
    resistance_ohm: float = 1.0641
    inductance_h: float = 175.8e-6


@dataclass(frozen=True)
class Target:
    resistance_ohm: float
    inductance_h: float
    mutual_inductance_h: float

    def validate(self, coil: Coil) -> None:
        if self.resistance_ohm <= 0 or self.inductance_h <= 0:
            raise ValueError("Target R and L must be positive")
        if self.mutual_inductance_h < 0:
            raise ValueError("Mutual inductance must be non-negative")
        # A passive coupled-inductor model requires M^2 < L1*L2.
        if self.mutual_inductance_h ** 2 >= coil.inductance_h * self.inductance_h:
            raise ValueError("Unphysical coupling: require M^2 < Lcoil*Ltarget")


@dataclass(frozen=True)
class Pulse:
    voltage_v: float = 12.0
    on_time_s: float = 200e-6
    clamp_resistance_ohm: float = 20.0
    sample_start_s: float = 20e-6
    sample_stop_s: float = 500e-6
    time_step_s: float = 0.25e-6

    def validate(self) -> None:
        if self.voltage_v < 0:
            raise ValueError("voltage_v must be non-negative")
        if self.on_time_s <= 0 or self.clamp_resistance_ohm <= 0:
            raise ValueError("pulse duration and clamp resistance must be positive")
        if self.time_step_s <= 0:
            raise ValueError("time_step_s must be positive")
        if self.sample_start_s < 0 or self.sample_stop_s <= self.sample_start_s:
            raise ValueError("invalid sample window")


def _derivative(i_coil: float, i_target: float, coil: Coil,
                target: Target, source_v: float, series_r: float) -> tuple[float, float]:
    # [L1 M; M L2] [di1/dt; di2/dt] = [V - R1*i1; -R2*i2]
    a = source_v - series_r * i_coil
    b = -target.resistance_ohm * i_target
    determinant = coil.inductance_h * target.inductance_h - target.mutual_inductance_h ** 2
    di1 = (target.inductance_h * a - target.mutual_inductance_h * b) / determinant
    di2 = (coil.inductance_h * b - target.mutual_inductance_h * a) / determinant
    return di1, di2


def _rk4_step(i1: float, i2: float, dt: float, coil: Coil, target: Target,
              source_v: float, series_r: float) -> tuple[float, float]:
    f = lambda x, y: _derivative(x, y, coil, target, source_v, series_r)
    k1 = f(i1, i2)
    k2 = f(i1 + 0.5 * dt * k1[0], i2 + 0.5 * dt * k1[1])
    k3 = f(i1 + 0.5 * dt * k2[0], i2 + 0.5 * dt * k2[1])
    k4 = f(i1 + dt * k3[0], i2 + dt * k3[1])
    return (
        i1 + dt * (k1[0] + 2*k2[0] + 2*k3[0] + k4[0]) / 6.0,
        i2 + dt * (k1[1] + 2*k2[1] + 2*k3[1] + k4[1]) / 6.0,
    )


def simulate(coil: Coil, target: Target, pulse: Pulse) -> list[dict[str, float]]:
    """Simulate drive and clamp decay, then target-only open-coil RX decay.

    RX begins after the clamp phase when the primary winding is isolated.
    The reported RX voltage is the mutual emf generated by the remaining
    target current. Switch recovery, parasitic capacitance, real clamp
    topology, soil, distributed target currents and amplifier noise are absent.
    """
    target.validate(coil)
    pulse.validate()
    dt = pulse.time_step_s
    # Choose enough time for primary current to decay to a small residual.
    t_decay = max(10.0 * coil.inductance_h /
                  (coil.resistance_ohm + pulse.clamp_resistance_ohm), 20e-6)
    total = pulse.on_time_s + t_decay
    steps = math.ceil(total / dt)
    i1 = 0.0
    i2 = 0.0
    rows: list[dict[str, float]] = []

    for n in range(steps + 1):
        t = n * dt
        if t < pulse.on_time_s:
            source_v = pulse.voltage_v
            series_r = coil.resistance_ohm
            phase = 0.0
        else:
            source_v = 0.0
            series_r = coil.resistance_ohm + pulse.clamp_resistance_ohm
            phase = 1.0

        if n > 0:
            i1, i2 = _rk4_step(i1, i2, dt, coil, target, source_v, series_r)

        rows.append({
            "time_s": t,
            "phase": phase,
            "coil_current_a": i1,
            "target_current_a": i2,
        })

    # Once primary is isolated, target current decays with L2/R2.
    # Open-circuit coil voltage is M*d(i_target)/dt.
    t0 = rows[-1]["time_s"]
    i2_0 = rows[-1]["target_current_a"]
    tau = target.inductance_h / target.resistance_ohm
    rx_steps = math.ceil(pulse.sample_stop_s / dt)
    for n in range(1, rx_steps + 1):
        tr = n * dt
        i2_rx = i2_0 * math.exp(-tr / tau)
        di2_dt = -i2_rx / tau
        rows.append({
            "time_s": t0 + tr,
            "phase": 2.0,
            "coil_current_a": 0.0,
            "target_current_a": i2_rx,
            "rx_voltage_v": target.mutual_inductance_h * di2_dt,
        })
    return rows


def window_peak_abs(rows: Iterable[dict[str, float]], start_s: float,
                    stop_s: float) -> float:
    values = [
        abs(row.get("rx_voltage_v", 0.0))
        for row in rows
        if row["phase"] == 2.0 and start_s <= row["time_s"] <= stop_s
    ]
    return max(values, default=0.0)
